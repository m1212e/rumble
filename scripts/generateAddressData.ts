/**
 * Regenerates lib/scalars/addressData.ts from Google's Address Data Service.
 * Run with `bun run generate:address-data`. CI runs it before testing and building, so
 * releases always ship the current data.
 */
import { writeFile } from "node:fs/promises";

const SERVICE_URL = "https://chromium-i18n.appspot.com/ssl-address/data";
const OUT_FILE = new URL("../lib/scalars/addressData.ts", import.meta.url);

type ServiceEntry = {
  countries?: string;
  require?: string;
  zip?: string;
  zipex?: string;
  sub_keys?: string;
  sub_isoids?: string;
  sub_names?: string;
  sub_lnames?: string;
  sub_zips?: string;
  sub_zipexs?: string;
};

const splitList = (value?: string) => value?.split("~") ?? [];
// zipex lists several examples, one is enough for an error message
const firstExample = (zipex?: string) => zipex?.split(",")[0] || undefined;

async function fetchEntry(key: string): Promise<ServiceEntry> {
  const res = await fetch(key ? `${SERVICE_URL}/${key}` : SERVICE_URL);
  if (!res.ok) {
    throw new Error(`Fetching ${key} failed with ${res.status}`);
  }
  return res.json() as Promise<ServiceEntry>;
}

// The service publishes Java regexes, which the validator compiles as JS ones
function assertValidRegex(pattern: string, where: string) {
  try {
    new RegExp(pattern, "u");
  } catch (error) {
    throw new Error(`Pattern ${pattern} of ${where} is not a valid JS regex`, {
      cause: error,
    });
  }
}

const countryCodes = (await fetchEntry("")).countries!.split("~");
// ZZ holds the defaults for every field a country entry leaves out
const defaults = await fetchEntry("ZZ");

const data: Record<string, unknown> = {};
for (const code of countryCodes) {
  const entry = await fetchEntry(code);

  if (entry.zip) {
    assertValidRegex(entry.zip, code);
  }

  let regions: Record<string, unknown> | undefined;
  if (entry.sub_keys) {
    const keys = splitList(entry.sub_keys);
    const isoIds = splitList(entry.sub_isoids);
    const names = splitList(entry.sub_names);
    const latinNames = splitList(entry.sub_lnames);
    const zips = splitList(entry.sub_zips);
    const zipExamples = splitList(entry.sub_zipexs);
    regions = {};
    // findRegionCode resolves codes and names case-insensitively, so each may only point to one region
    const regionCodesByName = new Map<string, string>();
    for (const [i, key] of keys.entries()) {
      // ISO 3166-2 ids where available, so e.g. China takes "AH" instead of "安徽省"
      const regionCode = (isoIds[i] || key).toUpperCase();
      const zip = zips[i] || undefined;
      if (zip) {
        assertValidRegex(zip, `${code}/${key}`);
      }
      const aliases = [
        ...new Set(
          [key, names[i], latinNames[i]]
            .filter((name): name is string => !!name)
            .filter((name) => name.toUpperCase() !== regionCode),
        ),
      ];
      for (const name of [regionCode, ...aliases]) {
        const existing = regionCodesByName.get(name.toUpperCase());
        if (existing) {
          throw new Error(
            `${code}: "${name}" of region ${regionCode} is already used by region ${existing}`,
          );
        }
        regionCodesByName.set(name.toUpperCase(), regionCode);
      }
      regions[regionCode] = {
        zip,
        zipex: firstExample(zipExamples[i]),
        names: aliases.length ? aliases : undefined,
      };
    }
  }

  data[code] = {
    require: entry.require ?? defaults.require!,
    zip: entry.zip,
    zipex: firstExample(entry.zipex),
    regions,
  };
}

// The attribution is a /*! legal comment */ because bundlers drop plain comments from their output
const source = `// Generated by scripts/generateAddressData.ts, do not edit by hand.

export type RegionAddressRules = {
  /** Regex the postal code must start with. */
  zip?: string;
  /** Example postal code within the region. */
  zipex?: string;
  /** Other names the region is known by, e.g. "California" for CA. */
  names?: string[];
};

export type CountryAddressRules = {
  /** One-letter codes of the required fields, see the libaddressinput metadata docs. */
  require: string;
  /** Regex the whole postal code must match. */
  zip?: string;
  /** Example postal code. */
  zipex?: string;
  /** Regions by their upper-cased code. */
  regions?: Record<string, RegionAddressRules>;
};

/*! Address data derived from Google's Address Data Service (https://github.com/google/libaddressinput),
 * licensed under CC-BY 4.0 (https://creativecommons.org/licenses/by/4.0/).
 * Changes: reduced to required fields, postal code patterns and examples, and regions with
 * their names, with region codes upper-cased and ISO 3166-2 ids used where available. */
export const addressData: Record<string, CountryAddressRules> = ${JSON.stringify(data, null, 2)};
`;

await writeFile(OUT_FILE, source);
console.log(`Wrote rules for ${countryCodes.length} countries`);
